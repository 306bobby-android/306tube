package tube.three06.player

import kotlinx.coroutines.flow.StateFlow
import tube.three06.innertube.model.Video

data class PlayerState(
    val current: Video? = null,
    val status: Status = Status.IDLE,
    val isPlaying: Boolean = false,
    val positionMs: Long = 0L,
    val bufferedPositionMs: Long = 0L,
    val durationMs: Long = 0L,
    val speed: Float = 1.0f,
    val quality: QualitySelection = QualitySelection.Auto,
    val availableQualities: List<QualityOption> = emptyList(),
    val activeHeight: Int = 0,
    val captions: List<CaptionOption> = emptyList(),
    val selectedCaption: String? = null,
    val audioTracks: List<AudioTrackOption> = emptyList(),
    val selectedAudioTrack: String? = null,
    val loop: LoopMode = LoopMode.OFF,
    val autoplay: Boolean = true,
    val autoplayCountdownMs: Long = 8000L,
    val audioOnly: Boolean = false,
    val isLive: Boolean = false,
    val error: PlayerError? = null,
    val lastSkippedSegment: SkipSegment? = null,
    val segments: List<SkipSegment> = emptyList(),
    val upNext: Video? = null,
    val upNextAtMillis: Long = 0L,
    val upNextPaused: Boolean = false,
) {
    enum class Status { IDLE, RESOLVING, BUFFERING, READY, ENDED, ERROR }
}

data class PlayerError(
    val message: String,
    val recoverable: Boolean,
    val cause: Throwable? = null,
)

sealed interface QualitySelection {
    data object Auto : QualitySelection

    data class Height(val maxHeight: Int) : QualitySelection
}

data class QualityOption(val height: Int, val fps: Int, val label: String)

data class CaptionOption(val languageCode: String, val name: String, val autoGenerated: Boolean)

data class AudioTrackOption(val languageCode: String, val name: String, val isDefault: Boolean)

enum class LoopMode { OFF, ONE, ALL }

data class SkipSegment(
    val startMs: Long,
    val endMs: Long,
    val category: String,
    val uuid: String,
    val skip: Boolean = true,
)

data class PlayQueue(
    val items: List<Video> = emptyList(),
    val currentIndex: Int = -1,
)

interface PlayerController {
    val state: StateFlow<PlayerState>
    val queue: StateFlow<PlayQueue>

    fun play(video: Video, queue: List<Video> = listOf(video), startPositionMs: Long = 0L)
    fun playQueue(queue: List<Video>, startIndex: Int, startPositionMs: Long = 0L)
    fun enqueue(video: Video, playNext: Boolean = false)
    fun removeFromQueue(index: Int)
    fun moveInQueue(from: Int, to: Int)

    fun togglePlayPause()
    fun pause()
    fun resume()
    fun seekTo(positionMs: Long)
    fun seekBy(deltaMs: Long)
    fun next()
    fun previous()
    fun stop()

    fun setQuality(selection: QualitySelection)
    fun setSpeed(speed: Float)
    fun setCaptions(languageCode: String?)
    fun setAudioTrack(languageCode: String?)
    fun setLoop(mode: LoopMode)
    fun setAutoplay(enabled: Boolean)
    fun setAutoplayCountdown(millis: Long)
    fun setAudioOnly(enabled: Boolean)
    fun setSkipSegments(videoId: String, segments: List<SkipSegment>)

    fun playUpNext()
    fun cancelUpNext()
    fun holdUpNext(hold: Boolean)
}
