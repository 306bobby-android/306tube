package tube.three06.player.internal

import tube.three06.player.AudioTrackOption
import tube.three06.player.CaptionOption
import tube.three06.player.QualityOption
import tube.three06.player.QualitySelection
import tube.three06.player.ResolvedStreams

internal object QualityMapping {

    fun qualityOptions(streams: ResolvedStreams): List<QualityOption> {
        val source = streams.videoStreams.filter { !it.hasAudio }.ifEmpty { streams.muxedStreams }
        return source
            .filter { it.height > 0 }
            .groupBy { it.height }
            .map { (height, group) ->
                val best = group.maxBy { it.fps }
                val fps = best.fps
                val label = best.qualityLabel.ifBlank {
                    if (fps > 30) "${height}p$fps" else "${height}p"
                }
                QualityOption(height, fps, label)
            }
            .sortedByDescending { it.height }
    }

    fun maxHeight(selection: QualitySelection): Int? = when (selection) {
        QualitySelection.Auto -> null
        is QualitySelection.Height -> selection.maxHeight.takeIf { it > 0 }
    }

    fun <T> pickByHeight(streams: List<T>, height: (T) -> Int, selection: QualitySelection): T? {
        if (streams.isEmpty()) return null
        val max = maxHeight(selection) ?: return streams.maxByOrNull(height)
        return streams.filter { height(it) <= max }.maxByOrNull(height)
            ?: streams.minByOrNull(height)
    }

    fun captionOptions(streams: ResolvedStreams): List<CaptionOption> =
        streams.captions
            .map { CaptionOption(it.languageCode, it.name, it.isAutoGenerated) }
            .distinctBy { it.languageCode to it.autoGenerated }
            .sortedWith(compareBy({ it.autoGenerated }, { it.name }))

    fun audioTrackOptions(streams: ResolvedStreams): List<AudioTrackOption> =
        streams.audioStreams
            .filter { it.languageCode != null }
            .groupBy { it.languageCode!! }
            .map { (language, group) ->
                AudioTrackOption(
                    language,
                    group.firstNotNullOfOrNull { it.trackName } ?: language,
                    group.any { it.isDefaultTrack },
                )
            }
            .sortedWith(compareBy({ !it.isDefault }, { it.name }))
}
