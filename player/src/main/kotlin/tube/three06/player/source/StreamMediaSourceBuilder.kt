package tube.three06.player.source

import android.content.Context
import android.net.Uri
import android.util.Log
import androidx.annotation.OptIn
import androidx.media3.common.C
import androidx.media3.common.Format
import androidx.media3.common.MediaItem
import androidx.media3.common.MimeTypes
import androidx.media3.common.util.UnstableApi
import androidx.media3.datasource.DataSource
import androidx.media3.datasource.DefaultDataSource
import androidx.media3.exoplayer.dash.DashMediaSource
import androidx.media3.exoplayer.dash.manifest.DashManifestParser
import androidx.media3.exoplayer.hls.HlsMediaSource
import androidx.media3.exoplayer.source.MediaSource
import androidx.media3.exoplayer.source.MergingMediaSource
import androidx.media3.exoplayer.source.ProgressiveMediaSource
import androidx.media3.extractor.ExtractorsFactory
import androidx.media3.extractor.text.DefaultSubtitleParserFactory
import androidx.media3.extractor.text.SubtitleExtractor
import okhttp3.OkHttpClient
import tube.three06.innertube.model.CaptionTrack
import tube.three06.player.QualitySelection
import tube.three06.player.ResolvedStreams
import tube.three06.player.StreamResolveException
import tube.three06.player.internal.DashManifestGenerator
import tube.three06.player.internal.QualityMapping
import tube.three06.player.offline.OfflineMedia

@OptIn(UnstableApi::class)
class StreamMediaSourceBuilder(
    private val context: Context,
    private val http: OkHttpClient,
) {
    private val manifestParser = DashManifestParser()
    private val subtitleParsers = DefaultSubtitleParserFactory()
    private var userAgent: String? = null

    private val dashDataSourceFactory: DataSource.Factory
        get() = factory(rangeParameter = true, rn = true)

    private val progressiveDataSourceFactory: DataSource.Factory
        get() = RangeChunkDataSource.Factory(factory(rangeParameter = true, rn = true))

    private val plainDataSourceFactory: DataSource.Factory
        get() = factory(rangeParameter = false, rn = false)

    private fun factory(rangeParameter: Boolean, rn: Boolean): DataSource.Factory {
        val factory = YoutubeHttpDataSource.Factory(http)
            .setRangeParameterEnabled(rangeParameter)
            .setRnParameterEnabled(rn)
        userAgent?.let { factory.setDefaultRequestProperties(mapOf("User-Agent" to it)) }
        return factory
    }

    class Built(val source: MediaSource, val adaptive: Boolean)

    fun build(streams: ResolvedStreams, mediaItem: MediaItem, quality: QualitySelection): Built {
        userAgent = streams.userAgent
        if (streams.isLive) return Built(buildLive(streams, mediaItem), adaptive = true)

        val (primary, adaptive) = buildVod(streams, mediaItem, quality)
        val captions = streams.captions.filter {
            it.baseUrl.startsWith("https://") || it.baseUrl.startsWith("http://")
        }
        if (captions.isEmpty()) return Built(primary, adaptive)

        val captionSources = captions.map { caption ->
            val format = subtitleFormat(caption)
            ProgressiveMediaSource.Factory(
                VttLayoutStrippingDataSource.Factory(plainDataSourceFactory, caption.isAutoGenerated),
                ExtractorsFactory { arrayOf(SubtitleExtractor(subtitleParsers.create(format), format)) },
            ).createMediaSource(MediaItem.fromUri(caption.baseUrl + "&fmt=vtt"))
        }
        return Built(MergingMediaSource(primary, *captionSources.toTypedArray()), adaptive)
    }

    fun buildOffline(media: OfflineMedia, mediaItem: MediaItem): MediaSource {
        userAgent = null
        val factory = ProgressiveMediaSource.Factory(DefaultDataSource.Factory(context))
        fun part(uri: String) = factory.createMediaSource(mediaItem.buildUpon().setUri(uri).build())

        val video = media.videoUri?.let(::part)
        val audio = media.audioUri?.let(::part)
        return when {
            video != null && audio != null -> MergingMediaSource(video, audio)
            video != null -> video
            audio != null -> audio
            else -> throw StreamResolveException("Download has no files")
        }
    }

    private fun buildLive(streams: ResolvedStreams, mediaItem: MediaItem): MediaSource {
        streams.hlsManifestUrl?.let { hls ->
            val item = mediaItem.buildUpon()
                .setUri(hls)
                .setMimeType(MimeTypes.APPLICATION_M3U8)
                .setLiveConfiguration(
                    MediaItem.LiveConfiguration.Builder().setTargetOffsetMs(LIVE_EDGE_GAP_MS).build(),
                )
                .build()
            return HlsMediaSource.Factory(plainDataSourceFactory)
                .setAllowChunklessPreparation(true)
                .createMediaSource(item)
        }
        streams.dashManifestUrl?.let { dash ->
            val item = mediaItem.buildUpon()
                .setUri(dash)
                .setMimeType(MimeTypes.APPLICATION_MPD)
                .build()
            return DashMediaSource.Factory(dashDataSourceFactory).createMediaSource(item)
        }
        throw StreamResolveException("Live stream has no manifest")
    }

    private fun buildVod(
        streams: ResolvedStreams,
        mediaItem: MediaItem,
        quality: QualitySelection,
    ): Pair<MediaSource, Boolean> {
        adaptiveDash(streams, mediaItem)?.let { return it to true }

        val video = QualityMapping.pickByHeight(
            streams.videoStreams.filter { !it.hasAudio },
            { it.height },
            quality,
        )
        val audio = streams.audioStreams
            .filter { it.isDefaultTrack }
            .ifEmpty { streams.audioStreams }
            .maxByOrNull { it.bitrate }

        if (video != null && audio != null) {
            return MergingMediaSource(
                progressive(mediaItem, video.url),
                progressive(mediaItem, audio.url),
            ) to false
        }

        QualityMapping.pickByHeight(streams.muxedStreams, { it.height }, quality)?.let {
            return progressive(mediaItem, it.url) to false
        }
        audio?.let { return progressive(mediaItem, it.url) to false }

        streams.hlsManifestUrl?.let { hls ->
            return HlsMediaSource.Factory(plainDataSourceFactory)
                .createMediaSource(mediaItem.buildUpon().setUri(hls).build()) to true
        }
        streams.dashManifestUrl?.let { dash ->
            return DashMediaSource.Factory(dashDataSourceFactory)
                .createMediaSource(mediaItem.buildUpon().setUri(dash).build()) to true
        }
        throw StreamResolveException("No playable streams")
    }

    private fun adaptiveDash(streams: ResolvedStreams, mediaItem: MediaItem): MediaSource? {
        if (DashManifestGenerator.eligibleVideo(streams).isEmpty() ||
            DashManifestGenerator.eligibleAudio(streams).isEmpty()
        ) {
            return null
        }
        val xml = DashManifestGenerator.generate(streams) ?: return null
        return try {
            val manifest = manifestParser.parse(
                Uri.parse(MANIFEST_BASE_URI),
                xml.toByteArray(Charsets.UTF_8).inputStream(),
            )
            DashMediaSource.Factory(dashDataSourceFactory).createMediaSource(manifest, mediaItem)
        } catch (e: Exception) {
            Log.w(TAG, "Generated DASH manifest rejected, falling back to progressive sources", e)
            null
        }
    }

    private fun progressive(mediaItem: MediaItem, url: String): MediaSource =
        ProgressiveMediaSource.Factory(progressiveDataSourceFactory)
            .createMediaSource(mediaItem.buildUpon().setUri(url).build())

    private fun subtitleFormat(caption: CaptionTrack): Format =
        Format.Builder()
            .setSampleMimeType(MimeTypes.TEXT_VTT)
            .setLanguage(caption.languageCode)
            .setLabel(caption.name)
            .setId(captionTrackId(caption))
            .setRoleFlags(
                if (caption.isAutoGenerated) C.ROLE_FLAG_TRANSCRIBES_DIALOG else C.ROLE_FLAG_SUBTITLE,
            )
            .build()

    companion object {
        private const val TAG = "StreamMediaSourceBuilder"
        private const val MANIFEST_BASE_URI = "https://www.youtube.com/"
        private const val LIVE_EDGE_GAP_MS = 10_000L

        fun captionTrackId(caption: CaptionTrack): String =
            if (caption.isAutoGenerated) "${caption.languageCode}.asr" else caption.languageCode
    }
}
