package tube.three06.innertube.model

data class PlayerResponse(
    val videoId: String,
    val playability: Playability,
    val formats: List<StreamFormat>,
    val adaptiveFormats: List<StreamFormat>,
    val hlsManifestUrl: String?,
    val dashManifestUrl: String?,
    val captions: List<CaptionTrack>,
    val storyboardSpec: String?,
    val lengthSeconds: Long?,
    val isLive: Boolean,
    val title: String?,
    val channelId: String?,
    val author: String?,
    val keywords: List<String>,
    val shortDescription: String?,
    val thumbnails: List<Thumbnail>,
    val playbackTracking: PlaybackTracking?,
    val expiresInSeconds: Long?,
    val clientUsed: String,
    val serverAbrStreamingUrl: String? = null,
    val startSeconds: Long? = null,
)

data class Playability(val status: String, val reason: String? = null) {
    val ok: Boolean get() = status == "OK"
}

data class StreamFormat(
    val itag: Int,
    val url: String?,
    val signatureCipher: String?,
    val mimeType: String,
    val bitrate: Long?,
    val averageBitrate: Long?,
    val width: Int?,
    val height: Int?,
    val fps: Int?,
    val qualityLabel: String?,
    val quality: String?,
    val audioQuality: String?,
    val audioSampleRate: Int?,
    val audioChannels: Int?,
    val contentLength: Long?,
    val approxDurationMs: Long?,
    val audioTrack: AudioTrack?,
    val initRange: ByteRange?,
    val indexRange: ByteRange?,
    val isDrc: Boolean = false,
    val xtags: String? = null,
) {
    val isVideo: Boolean get() = mimeType.startsWith("video/")
    val isAudio: Boolean get() = mimeType.startsWith("audio/")
    val codecs: String? get() = Regex("codecs=\"([^\"]+)\"").find(mimeType)?.groupValues?.get(1)
}

data class ByteRange(val start: Long, val end: Long)

data class AudioTrack(
    val id: String?,
    val displayName: String?,
    val languageCode: String?,
    val isDefault: Boolean,
)

data class CaptionTrack(
    val baseUrl: String,
    val languageCode: String,
    val name: String,
    val kind: String?,
    val isTranslatable: Boolean,
    val vssId: String?,
) {
    val isAutoGenerated: Boolean get() = kind == "asr"
}

data class PlaybackTracking(
    val videostatsPlaybackUrl: String?,
    val videostatsWatchtimeUrl: String?,
    val ptrackingUrl: String?,
    val qoeUrl: String?,
    val atrUrl: String?,
)
